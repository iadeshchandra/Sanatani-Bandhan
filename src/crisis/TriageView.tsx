/**
 * TriageView — the urgency-sorted incident queue.
 * =========================================================================
 * Sort: triageScore = severityWeight (critical=100, high=50, medium=20)
 * + minutes waiting. Most urgent first. "Time waiting" ticks live (30s).
 * Rows: situation icon, name, live wait time, ack count, quick actions
 * (acknowledge, open details). ≥44px targets, mobile-first.
 */
import React, { useEffect, useMemo, useState } from 'react';
import { BadgeCheck, ChevronRight, Loader2, Users } from 'lucide-react';
import type { CrisisAccess, CrisisEvent } from './crisisCommandTypes';
import { tsToMs } from './crisisCommandTypes';
import { useCrisisT } from './crisisI18n';
import { triageScore, minutesWaiting } from './crisisIntelligence';
import { acknowledgeEvent, type Actor } from './crisisActions';
import { SITUATION_ICON, SEVERITY_STYLE } from './crisisShared';

interface Props {
  events: CrisisEvent[];
  access: CrisisAccess;
  actor: Actor;
  onSelect: (e: CrisisEvent) => void;
}

export const TriageView: React.FC<Props> = ({ events, access, actor, onSelect }) => {
  const t = useCrisisT();
  const [now, setNow] = useState(() => Date.now());
  const [acking, setAcking] = useState<string | null>(null);

  // Live-ticking wait clock.
  useEffect(() => {
    const id = window.setInterval(() => setNow(Date.now()), 30000);
    return () => window.clearInterval(id);
  }, []);

  const sorted = useMemo(
    () =>
      [...events].sort(
        (a, b) => triageScore(b, now) - triageScore(a, now),
      ),
    [events, now],
  );

  const doAck = async (e: CrisisEvent, ev: React.MouseEvent) => {
    ev.stopPropagation();
    if (!access.canAcknowledge || acking) return;
    setAcking(e.id);
    try {
      await acknowledgeEvent(e, actor);
    } catch {
      /* toast handled by drawer; row-level ack stays silent-safe */
    } finally {
      setAcking(null);
    }
  };

  if (sorted.length === 0) {
    return (
      <div className="rounded-3xl bg-[#FFFBEB] border border-amber-200/70 shadow-[0_8px_30px_rgba(180,83,9,0.08)] px-6 py-14 text-center">
        <div className="text-5xl mb-4" aria-hidden>
          🙏
        </div>
        <p className="text-[16px] text-[#92400E] font-semibold leading-relaxed">{t('triage.empty')}</p>
      </div>
    );
  }

  return (
    <ul className="space-y-3">
      {sorted.map((e, idx) => {
        const wait = Math.floor(minutesWaiting(e, now));
        const waitLabel =
          wait < 1 ? t('misc.justNow') : wait < 60 ? `${wait} ${t('misc.minAgo')}` : `${Math.floor(wait / 60)} ${t('misc.hrAgo')}`;
        return (
          <li key={e.id}>
            <button
              type="button"
              onClick={() => onSelect(e)}
              className="w-full text-left bg-white border border-stone-200 rounded-3xl p-4 shadow-sm active:scale-[0.99] transition min-h-[88px]"
            >
              <div className="flex items-center gap-3">
                {/* rank + icon */}
                <div className="flex flex-col items-center gap-1 shrink-0">
                  <span className="text-[11px] font-bold text-stone-400">#{idx + 1}</span>
                  <span className={`p-2.5 rounded-2xl ${SEVERITY_STYLE[e.severity] ?? 'bg-stone-500 text-white'}`}>
                    {SITUATION_ICON[e.situation]}
                  </span>
                </div>

                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 flex-wrap">
                    <p className="font-bold text-[16px] text-stone-900 truncate">
                      {e.senderName}
                    </p>
                    <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full ${SEVERITY_STYLE[e.severity] ?? ''}`}>
                      {t(`sev.${e.severity}`)}
                    </span>
                    {e.autoGenerated ? (
                      <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-purple-100 text-purple-800">
                        {t('triage.autoCrowd')}
                      </span>
                    ) : null}
                  </div>
                  <p className="text-[13px] text-stone-500 truncate mt-0.5">
                    {t(`sit.${e.situation}`)} · {e.details || t('triage.tapDetails')}
                  </p>
                  <div className="flex items-center gap-3 mt-1.5 text-[12px] text-stone-500">
                    <span className={`font-bold ${wait >= 10 && e.severity === 'critical' ? 'text-red-600' : 'text-stone-700'}`}>
                      ⏱ {waitLabel} {t('triage.waiting')}
                    </span>
                    <span>✓ {e.ackCount ?? 0} {t('triage.acks')}</span>
                    <span className="inline-flex items-center gap-1">
                      <Users size={12} /> {e.responderCount ?? 0} {t('triage.responders')}
                    </span>
                  </div>
                </div>

                <ChevronRight size={20} className="text-stone-300 shrink-0" />
              </div>

              {/* quick actions */}
              <div className="flex gap-2 mt-3" onClick={(ev) => ev.stopPropagation()}>
                {access.canAcknowledge && e.status === 'active' ? (
                  <button
                    type="button"
                    onClick={(ev) => doAck(e, ev)}
                    disabled={acking === e.id}
                    className="min-h-[48px] flex-1 rounded-2xl bg-gradient-to-br from-amber-700 to-amber-900 text-amber-50 font-bold text-[15px] flex items-center justify-center gap-2 active:scale-[0.98] disabled:opacity-50 shadow-[0_4px_14px_rgba(180,83,9,0.35)]"
                  >
                    {acking === e.id ? (
                      <Loader2 size={18} className="animate-spin" aria-hidden />
                    ) : (
                      <>
                        <BadgeCheck size={18} aria-hidden />
                        {t('act.acknowledge')}
                      </>
                    )}
                  </button>
                ) : null}
                <button
                  type="button"
                  onClick={() => onSelect(e)}
                  className="min-h-[48px] flex-1 rounded-2xl bg-stone-100 text-stone-800 font-bold text-[15px] active:scale-[0.98]"
                >
                  {t('triage.tapDetails')}
                </button>
              </div>
            </button>
          </li>
        );
      })}
    </ul>
  );
};
