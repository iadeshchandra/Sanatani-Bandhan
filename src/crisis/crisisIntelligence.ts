/**
 * Crisis Command — intelligence layer.
 * =========================================================================
 * 1. triageScore(event): severity weight + minutes waiting. The triage
 *    queue sorts by this, most urgent first.
 * 2. checkCrowdDensity(...): stampede prevention for temple festivals.
 *    When ≥3 active SOS events land within 100 m of each other inside a
 *    5-minute window, it creates/updates a synthetic critical 'crowd' event
 *    linked to the real ones — so the command dashboard treats a forming
 *    crowd crush as its own top-priority incident.
 *
 * This is a client-side best-effort helper (called from the dashboard when
 * new events arrive). A Cloud Function would be the hardened home for it;
 * see the rules author notes in the parent handoff.
 */
import {
  addDoc,
  collection,
  doc,
  getDocs,
  query,
  serverTimestamp,
  updateDoc,
  where,
} from 'firebase/firestore';
import { db } from '../firebase';
import type { CrisisEvent } from './crisisCommandTypes';
import { tsToMs, isActiveEvent } from './crisisCommandTypes';

const SEVERITY_WEIGHT: Record<CrisisEvent['severity'], number> = {
  critical: 100,
  high: 50,
  medium: 20,
};

export function severityWeight(severity: CrisisEvent['severity']): number {
  return SEVERITY_WEIGHT[severity] ?? 0;
}

/** Minutes the event has been waiting (from createdAt until now / resolvedAt). */
export function minutesWaiting(event: CrisisEvent, nowMs = Date.now()): number {
  const start = tsToMs(event.createdAt);
  if (!start) return 0;
  const end = event.resolvedAt ? tsToMs(event.resolvedAt) : nowMs;
  return Math.max(0, (end - start) / 60000);
}

/**
 * score = severityWeight (critical=100, high=50, medium=20) + minutesWaiting.
 * A critical event always outranks a high one until ~50 minutes of waiting
 * close the gap — deliberate: severity dominates, waiting breaks ties.
 */
export function triageScore(event: CrisisEvent, nowMs = Date.now()): number {
  return severityWeight(event.severity) + minutesWaiting(event, nowMs);
}

/** Haversine distance in metres between two lat/lng points. */
export function distanceM(
  aLat: number,
  aLng: number,
  bLat: number,
  bLng: number,
): number {
  const R = 6371000;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(bLat - aLat);
  const dLng = toRad(bLng - aLng);
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(aLat)) * Math.cos(toRad(bLat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
}

const CROWD_WINDOW_MS = 5 * 60 * 1000;
const CROWD_RADIUS_M = 100;
const CROWD_MIN_EVENTS = 3;

interface DensityCheckInput {
  orgId: string;
  workspaceId: string;
  /** Optional trigger event (the SOS that just arrived). */
  triggerEvent?: CrisisEvent;
}

/**
 * Scans recent active events for a forming crowd crush.
 * Returns the synthetic crowd event id when one was created/updated,
 * or null when there is nothing to escalate.
 */
export async function checkCrowdDensity({
  orgId,
  workspaceId,
  triggerEvent,
}: DensityCheckInput): Promise<string | null> {
  const windowStart = Date.now() - CROWD_WINDOW_MS;

  // Pull the org's active events. We filter recency client-side so the
  // query needs no composite index beyond (workspaceId).
  const q = query(
    collection(db, 'crisis_events'),
    where('workspaceId', '==', workspaceId),
  );
  const snap = await getDocs(q);

  const recent: CrisisEvent[] = [];
  snap.forEach((d) => {
    const e = { id: d.id, ...(d.data() as Omit<CrisisEvent, 'id'>) } as CrisisEvent;
    if (e.autoGenerated) return; // synthetic events don't seed clusters
    if (!isActiveEvent(e)) return;
    if (!e.location || typeof e.location.lat !== 'number') return;
    if (tsToMs(e.createdAt) < windowStart) return;
    recent.push(e);
  });
  if (triggerEvent && !recent.some((e) => e.id === triggerEvent.id)) {
    recent.push(triggerEvent);
  }
  if (recent.length < CROWD_MIN_EVENTS) return null;

  // Greedy clustering: any two events within 100 m share a cluster.
  const clusters: CrisisEvent[][] = [];
  for (const e of recent) {
    let placed = false;
    for (const c of clusters) {
      if (
        c.some(
          (m) =>
            m.location &&
            e.location &&
            distanceM(m.location.lat, m.location.lng, e.location.lat, e.location.lng) <=
              CROWD_RADIUS_M,
        )
      ) {
        c.push(e);
        placed = true;
        break;
      }
    }
    if (!placed) clusters.push([e]);
  }

  const dense = clusters.find((c) => c.length >= CROWD_MIN_EVENTS);
  if (!dense) return null;

  // Centroid of the cluster.
  const centroid = dense.reduce(
    (acc, e) => ({
      lat: acc.lat + (e.location?.lat ?? 0) / dense.length,
      lng: acc.lng + (e.location?.lng ?? 0) / dense.length,
    }),
    { lat: 0, lng: 0 },
  );
  const linkedEventIds = dense.map((e) => e.id).sort();

  // Is there already an ACTIVE synthetic crowd event near this centroid?
  const existingQ = query(
    collection(db, 'crisis_events'),
    where('workspaceId', '==', workspaceId),
    where('autoGenerated', '==', true),
    where('situation', '==', 'crowd'),
  );
  const existing = await getDocs(existingQ);
  let existingId: string | null = null;
  existing.forEach((d) => {
    if (existingId) return;
    const data = d.data() as Partial<CrisisEvent>;
    const st = data.status as string | undefined;
    if (st !== 'active' && st !== 'acknowledged' && st !== 'responding') return;
    const loc = data.location;
    if (loc && distanceM(loc.lat, loc.lng, centroid.lat, centroid.lng) <= CROWD_RADIUS_M) {
      existingId = d.id;
    }
  });

  if (existingId) {
    // Update the linked set — union with what is already recorded.
    const prev = existing.docs.find((d) => d.id === existingId);
    const prevIds = ((prev?.data() as Partial<CrisisEvent>)?.linkedEventIds ?? []) as string[];
    const merged = Array.from(new Set([...prevIds, ...linkedEventIds])).sort();
    await updateDoc(doc(db, 'crisis_events', existingId), {
      linkedEventIds: merged,
      location: {
        lat: centroid.lat,
        lng: centroid.lng,
        address: 'Auto-detected crowd density',
        capturedAt: Date.now(),
      },
      updatedAt: Date.now(),
    });
    return existingId;
  }

  const ref = await addDoc(collection(db, 'crisis_events'), {
    senderUid: 'system',
    senderName: 'Crowd-density monitor',
    situation: 'crowd',
    severity: 'critical',
    status: 'active',
    details: `Auto-detected: ${dense.length} SOS events within ${CROWD_RADIUS_M} m in the last 5 minutes. Possible crowd crush forming.`,
    location: {
      lat: centroid.lat,
      lng: centroid.lng,
      address: 'Auto-detected crowd density',
      capturedAt: Date.now(),
    },
    orgId,
    workspaceId,
    autoGenerated: true,
    linkedEventIds,
    ackCount: 0,
    responderCount: 0,
    createdAt: serverTimestamp(),
  });
  return ref.id;
}
