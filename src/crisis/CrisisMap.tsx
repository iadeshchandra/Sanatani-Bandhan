/**
 * CrisisMap — live crisis map, offline-first.
 * =========================================================================
 * Deliberately NO Leaflet/CDN tiles: at a festival with patchy data the
 * command dashboard must still render. This is a schematic SVG: the org
 * centre with distance rings, and SOS pins positioned by relative lat/lng
 * offset (metres). Colour = severity: red critical, orange high,
 * yellow medium. ≥44px tap targets on every pin.
 */
import React, { useMemo } from 'react';
import { MapPin } from 'lucide-react';
import type { CrisisEvent } from './crisisCommandTypes';
import { useCrisisT } from './crisisI18n';

const PIN_FILL: Record<string, string> = {
  critical: '#dc2626',
  high: '#ea580c',
  medium: '#eab308',
};

const W = 400;
const H = 300;
const CX = W / 2;
const CY = H / 2;
const MAX_PX = 130;

interface Pinned {
  event: CrisisEvent;
  x: number;
  y: number;
  distM: number;
}

function toMeters(lat: number, lng: number, cLat: number, cLng: number) {
  const dx = (lng - cLng) * 111320 * Math.cos((cLat * Math.PI) / 180);
  const dy = -(lat - cLat) * 111320; // SVG y grows downward
  return { dx, dy, distM: Math.hypot(dx, dy) };
}

interface Props {
  events: CrisisEvent[];
  onSelect: (e: CrisisEvent) => void;
  centerLabel?: string;
}

export const CrisisMap: React.FC<Props> = ({ events, onSelect, centerLabel }) => {
  const t = useCrisisT();

  const located = useMemo(
    () =>
      events.filter(
        (e) => e.location && typeof e.location.lat === 'number' && typeof e.location.lng === 'number',
      ),
    [events],
  );

  const model = useMemo(() => {
    if (located.length === 0) return null;
    const cLat = located.reduce((s, e) => s + (e.location?.lat ?? 0), 0) / located.length;
    const cLng = located.reduce((s, e) => s + (e.location?.lng ?? 0), 0) / located.length;
    const raw = located.map((event) => {
      const { dx, dy, distM } = toMeters(event.location!.lat, event.location!.lng, cLat, cLng);
      return { event, dx, dy, distM };
    });
    const maxDist = Math.max(60, ...raw.map((r) => r.distM));
    const scale = MAX_PX / maxDist;
    const pins: Pinned[] = raw.map((r) => ({
      event: r.event,
      x: CX + r.dx * scale,
      y: CY + r.dy * scale,
      distM: r.distM,
    }));
    return { pins, maxDist, scale };
  }, [located]);

  if (!model) {
    return (
      <div className="flex flex-col items-center justify-center py-16 text-stone-400">
        <MapPin size={40} className="mb-3 opacity-40" />
        <p className="text-[15px]">{t('map.empty')}</p>
      </div>
    );
  }

  const ringMeters = [50, 100, 200].filter((r) => r <= model.maxDist * 1.15);

  return (
    <div>
      <svg
        viewBox={`0 0 ${W} ${H}`}
        className="w-full h-auto rounded-3xl border border-stone-200"
        role="img"
        aria-label={t('tab.map')}
        style={{ background: 'linear-gradient(135deg, #faf7f2 0%, #f5efe6 100%)' }}
      >
        {/* distance rings */}
        {ringMeters.map((r) => (
          <g key={r}>
            <circle cx={CX} cy={CY} r={r * model.scale} fill="none" stroke="#d6c9b8" strokeWidth="1" strokeDasharray="4 4" />
            <text x={CX + r * model.scale - 4} y={CY - 4} fontSize="9" fill="#a89f91" textAnchor="end">
              {r} m
            </text>
          </g>
        ))}

        {/* org centre */}
        <g>
          <circle cx={CX} cy={CY} r="16" fill="#1c1917" opacity="0.08" />
          <circle cx={CX} cy={CY} r="7" fill="#b45309" stroke="#fff" strokeWidth="2" />
          <text x={CX} y={CY + 26} fontSize="10" fill="#78716c" textAnchor="middle" fontWeight="700">
            {centerLabel || t('map.orgCenter')}
          </text>
        </g>

        {/* pins */}
        {model.pins.map(({ event, x, y, distM }) => {
          const fill = PIN_FILL[event.severity] ?? '#78716c';
          const critical = event.severity === 'critical';
          const big = event.autoGenerated;
          return (
            <g
              key={event.id}
              onClick={() => onSelect(event)}
              className="cursor-pointer"
              role="button"
              aria-label={`${event.senderName} — ${event.situation} — ${event.severity}`}
              tabIndex={0}
              onKeyDown={(e) => {
                if (e.key === 'Enter' || e.key === ' ') onSelect(event);
              }}
            >
              {/* 44px tap target */}
              <circle cx={x} cy={y} r="22" fill="transparent" />
              {critical ? (
                <circle cx={x} cy={y} r={big ? 20 : 15} fill={fill} opacity="0.25">
                  <animate attributeName="r" values={big ? '16;24;16' : '12;19;12'} dur="1.6s" repeatCount="indefinite" />
                  <animate attributeName="opacity" values="0.35;0.08;0.35" dur="1.6s" repeatCount="indefinite" />
                </circle>
              ) : null}
              <circle
                cx={x}
                cy={y - (big ? 12 : 9)}
                r={big ? 11 : 8}
                fill={fill}
                stroke="#fff"
                strokeWidth="2.5"
                style={{ filter: 'drop-shadow(0 2px 3px rgba(0,0,0,0.25))' }}
              />
              <path
                d={`M ${x - 6} ${y - (big ? 4 : 2)} L ${x} ${y + (big ? 10 : 7)} L ${x + 6} ${y - (big ? 4 : 2)} Z`}
                fill={fill}
                stroke="#fff"
                strokeWidth="1.5"
              />
              <text
                x={x}
                y={y + (big ? 24 : 21)}
                fontSize="9.5"
                fill="#44403c"
                textAnchor="middle"
                fontWeight="700"
              >
                {Math.round(distM)} m
              </text>
            </g>
          );
        })}
      </svg>

      {/* legend */}
      <div className="flex items-center justify-center gap-4 mt-3 text-[13px] text-stone-600">
        {(['critical', 'high', 'medium'] as const).map((s) => (
          <span key={s} className="inline-flex items-center gap-1.5">
            <span className="w-3 h-3 rounded-full" style={{ background: PIN_FILL[s] }} />
            {t(`map.legend${s[0].toUpperCase()}${s.slice(1)}`)}
          </span>
        ))}
      </div>
      <p className="text-center text-[12px] text-stone-400 mt-1">{t('map.tapPin')}</p>
    </div>
  );
};
