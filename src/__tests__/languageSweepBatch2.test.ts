describe('batch-2 new surfaces keys (en/hi/bn authored)', () => {
  it('every new key resolves to a non-empty string in all three languages', () => {
    const bad: string[] = [];
    for (const key of NEW_KEYS) {
      const frags = FRAGS[BUCKET_FRAG[key.split('.')[1]]];
      const vals = frags.map((f) => get(f, key));
      if (vals.some((v) => typeof v !== 'string' || v.length === 0)) bad.push(key);
    }
    expect(bad).toEqual([]);
  });
  it('hi/bn are real translations, not English copies (allowlist aside)', () => {
    const bad: string[] = [];
    for (const key of NEW_KEYS) {
      const frags = FRAGS[BUCKET_FRAG[key.split('.')[1]]];
      const [en, hi, bn] = frags.map((f) => get(f, key));
      if (hi === en && !HI_IDENTICAL_OK.includes(key)) bad.push(`hi:${key}`);
      if (bn === en && !BN_IDENTICAL_OK.includes(key)) bad.push(`bn:${key}`);
    }
    expect(bad).toEqual([]);
  });
  it('each batch-2 bucket carries identical key sets in en/hi/bn', () => {
    for (const [bucket, frag] of Object.entries(BUCKET_FRAG)) {
      const sets = FRAGS[frag].map((f) => Object.keys(get(f, `surfaces.${bucket}`) ?? {}).sort());
      expect(sets[1]).toEqual(sets[0]);
      expect(sets[2]).toEqual(sets[0]);
    }
  });
});

