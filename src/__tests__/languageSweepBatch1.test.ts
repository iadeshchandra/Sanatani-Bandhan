import * as fs from 'fs';
import * as path from 'path';
import { SUPPORTED_LANGUAGES } from '../i18n/schema';
import { core as enCore } from '../i18n/lang/en/core';
import { core as hiCore } from '../i18n/lang/hi/core';
import { core as bnCore } from '../i18n/lang/bn/core';

const SRC = path.resolve(__dirname, '..');
const read = (rel: string) => fs.readFileSync(path.join(SRC, rel), 'utf8');

describe('registry unification', () => {
  it('registry carries the 10 languages with Sanskrit last', () => {
    expect(SUPPORTED_LANGUAGES.map((l) => l.code)).toEqual([
      'en', 'hi', 'bn', 'ta', 'te', 'mr', 'gu', 'kn', 'ml', 'sa',
    ]);
  });
  it('LanguageSwitcher renders the canonical registry, no local list', () => {
    const src = read('components/LanguageSwitcher.tsx');
    expect(src).toContain("from '../i18n/schema'");
    expect(src).toContain('SUPPORTED_LANGUAGES');
    expect(src).not.toMatch(/const\s+LANGUAGES\s*[:=]/);
    expect(src).not.toContain("code: 'sa', label");
  });
});

describe('surfaces + vibe dict completeness (en/hi/bn authored)', () => {
  const surfacesOf = (core: any) => core.surfaces as Record<string, Record<string, string>>;
  it('all three fragments carry identical surfaces key sets, all non-empty', () => {
    const en = surfacesOf(enCore); const hi = surfacesOf(hiCore); const bn = surfacesOf(bnCore);
    const keysOf = (s: typeof en) => Object.keys(s).flatMap((b) => Object.keys(s[b]).map((leaf) => `${b}.${leaf}`)).sort();
    expect(keysOf(hi)).toEqual(keysOf(en));
    expect(keysOf(bn)).toEqual(keysOf(en));
    expect(keysOf(en).length).toBe(416);
    for (const bucket of Object.keys(en)) {
      for (const leaf of Object.keys(en[bucket])) {
        for (const dict of [en, hi, bn]) {
          expect(typeof dict[bucket][leaf]).toBe('string');
          expect(dict[bucket][leaf].length).toBeGreaterThan(0);
        }
      }
    }
  });
  it('vibe greeting keys live in the runtime fragments', () => {
    for (const core of [enCore, hiCore, bnCore]) {
      const vibe = (core as any).vibe as Record<string, string>;
      // B1's five greeting keys + VIBE B2's ten (Your-usual headings,
      // offline sevak vocabulary, month-Panjika chrome) — the pin stays
      // an EXACT set equality, extended to the newly authored truth.
      expect(Object.keys(vibe).sort()).toEqual([
        'allSent', 'beginHere', 'greetAfternoon', 'greetEvening', 'greetMorning',
        'nextMonth', 'noFestival', 'offlineWorking', 'panjikaMonthTitle',
        'prevMonth', 'savedOnPhone', 'shubh', 'shubhMuhurat', 'today',
        'yourUsual',
      ]);
      for (const v of Object.values(vibe)) {
        expect(typeof v).toBe('string');
        expect(v.length).toBeGreaterThan(0);
      }
    }
  });
});

