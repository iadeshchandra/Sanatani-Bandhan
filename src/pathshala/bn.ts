/** Bengali digits for display. */
const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
export const toBnDigits = (n: number | string): string =>
  String(n).replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]);

/* ---------------- English number → words (Indian system) ---------------- */
const ONES = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine', 'Ten',
  'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
const TENS = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];
function enTwo(n: number): string {
  if (n < 20) return ONES[n];
  return TENS[Math.floor(n / 10)] + (n % 10 ? ' ' + ONES[n % 10] : '');
}
function enThree(n: number): string {
  const h = Math.floor(n / 100), r = n % 100;
  return (h ? ONES[h] + ' Hundred' + (r ? ' ' : '') : '') + (r ? enTwo(r) : '');
}
export function amountInWordsEn(n: number): string {
  if (n === 0) return 'Zero';
  const crore = Math.floor(n / 10000000); n %= 10000000;
  const lakh = Math.floor(n / 100000); n %= 100000;
  const thou = Math.floor(n / 1000); n %= 1000;
  const parts: string[] = [];
  if (crore) parts.push(enThree(crore) + ' Crore');
  if (lakh) parts.push(enTwo(lakh) + ' Lakh');
  if (thou) parts.push(enTwo(thou) + ' Thousand');
  if (n) parts.push(enThree(n));
  return parts.join(' ');
}

