export function pu(key: string, lang: string, vars?: Record<string, string>): string {
  const l = lang === 'bn' ? 'bn' : lang === 'hi' ? 'hi' : 'en';
  let s = STRINGS[l][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
